function [lhs, rhs] = static_resid(y, x, params)
T = NaN(4, 1);
lhs = NaN(15, 1);
rhs = NaN(15, 1);
T(1) = y(3)^params(2);
T(2) = y(11)^(-params(2));
T(3) = params(2)*params(6)*y(3)^(params(2)-1);
T(4) = y(11)^(1-params(2));
lhs(1) = 1/y(1);
rhs(1) = y(14);
lhs(2) = params(5)*y(2)^params(4);
rhs(2) = y(14)*y(8);
lhs(3) = y(14);
rhs(3) = y(14)*params(1)*(1+y(9)-params(3));
lhs(4) = y(1)+y(4)/(1-params(10));
rhs(4) = y(2)*y(8)+y(9)*y(3)/(1-params(10))-y(12);
lhs(5) = 1/y(5);
rhs(5) = y(15);
lhs(6) = params(5)*y(6)^params(4);
rhs(6) = y(8)*y(15);
lhs(7) = y(5);
rhs(7) = y(8)*y(6)-y(12);
lhs(8) = y(8);
rhs(8) = (1-params(2))*params(6)*T(1)*T(2);
lhs(9) = y(9);
rhs(9) = T(3)*T(4);
lhs(10) = y(7);
rhs(10) = T(4)*params(6)*T(1);
lhs(11) = y(12);
rhs(11) = y(13);
lhs(12) = log(y(13)/params(8));
rhs(12) = log(y(13)/params(8))*params(9)+x(1);
lhs(13) = y(10);
rhs(13) = y(1)*(1-params(10))+params(10)*y(5);
lhs(14) = y(11);
rhs(14) = y(2)*(1-params(10))+params(10)*y(6);
lhs(15) = y(3);
rhs(15) = y(4)+y(3)*(1-params(3));
end
