g1_v(17)=params(5)*getPowerDeriv(y(6),params(4),1);
g1_v(18)=(-y(8));
g1_v(19)=(-params(10));
g1_v(20)=1;
g1_v(21)=(-y(14));
g1_v(22)=(-y(2));
g1_v(23)=(-y(15));
